"""Generate the API reference page of the documentation site from the docstrings.

`griffe2md` renders the public API of `proclet` to Markdown; this script then adapts
the output to VitePress: each object heading gets an explicit `{#proclet.X}` anchor
matching the links `griffe2md` emits, and links to objects outside `proclet`
(`str`, `pathlib.Path`...) are turned into plain text. `griffe2md` has no template for
type aliases, so they are rendered here into a final "Types" section.
"""

import re
from pathlib import Path
from typing import Final

import griffe
from griffe2md import ConfigDict, render_package_docs

import proclet

ROOT_PATH: Final[Path] = Path(__file__).resolve().parent.parent
OUTPUT_PATH: Final[Path] = ROOT_PATH / "docs" / "reference" / "api.md"

CONFIG: Final[ConfigDict] = {
    "docstring_style": "google",
    "heading_level": 2,
    # Reading order of the page; type aliases go to the "Types" section.
    "members": [
        "Command",
        "Bind",
        "EnvCmd",
        "PathCmd",
        "strip_redirect",
        "ProcessObserver",
        "CommandNotFound",
        "ErrorReturnCode",
        "TimeoutException",
    ],
    "merge_init_into_class": True,
    "show_submodules": False,
    "summary": {
        "attributes": True,
        "classes": True,
        "functions": True,
        "modules": False,
    },
}

FRONT_MATTER: Final[str] = """---
title: API reference
outline: [2, 3]
---

<!-- Generated by `uv run poe docs:api` from the docstrings: do not edit. -->

"""

HEADING_RE: Final[re.Pattern[str]] = re.compile(r"^(#+) `([\w.]+)`$", re.MULTILINE)
LINK_RE: Final[re.Pattern[str]] = re.compile(r"\[([^\]]+)\]\(#([\w.]+)\)")


def _render_types() -> tuple[str, set[str]]:
    """Render the public type aliases of `proclet`.

    Returns:
        The Markdown "Types" section and the names it documents.
    """
    package = griffe.load("proclet", search_paths=[str(ROOT_PATH / "src")])
    lines = ["### Types {#types}", ""]
    names = set()
    for name in proclet.__all__:
        obj = package[name].final_target
        if obj.kind is not griffe.Kind.TYPE_ALIAS:
            continue
        names.add(name)
        docstring = obj.docstring.value if obj.docstring else ""
        lines += [
            f"#### `proclet.{name}` {{#proclet.{name}}}",
            "",
            "```python",
            f"type {name} = {obj.value}",
            "```",
            "",
            docstring,
            "",
        ]
    return "\n".join(lines), names


def render() -> str:
    """Render the API reference page.

    Returns:
        The Markdown page, front matter included.
    Raises:
        RuntimeError: if a name of `proclet.__all__` is missing from the page.
    """
    types, type_names = _render_types()
    missing = set(proclet.__all__) - set(CONFIG["members"]) - type_names
    if missing:
        raise RuntimeError(f"Add {sorted(missing)} to CONFIG['members']")
    text = render_package_docs("proclet", CONFIG).rstrip() + "\n\n" + types
    known = {name for _, name in HEADING_RE.findall(text)}
    text = HEADING_RE.sub(lambda m: f"{m[1]} `{m[2]}` {{#{m[2]}}}", text)
    text = LINK_RE.sub(lambda m: m[0] if m[2] in known else m[1], text)
    return FRONT_MATTER + text


def run() -> None:
    """Write the API reference page."""
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(render(), encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(ROOT_PATH)}")
